function inside(poly, lon, lat) {
  let in_ = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]
    const [xj, yj] = poly[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) in_ = !in_
  }
  return in_
}

/** Is (lon, lat), in degrees, land? */
export function isLand(lon, lat) {
  return LAND.some((poly) => inside(poly, lon, lat)) && !WATER.some((poly) => inside(poly, lon, lat))
}
